// Im Urlaub · Perfekt com sein
A(`
No dia 20 você aprendeu o Perfekt com **haben**. Hoje vem a outra metade: alguns verbos formam o passado com **sein**.
# Passo 1: a regra do movimento
Usam **sein** os verbos que levam o sujeito **de um lugar para outro** ou que mostram uma **mudança de estado**:
| Tipo | Verbos | Exemplo |
| movimento | gehen, fahren, fliegen, kommen, laufen, reisen | Ich bin nach Rom geflogen. |
| mudança de estado | aufstehen, einschlafen, aufwachen, werden, sterben | Ich bin um sechs aufgestanden. |
| exceções para decorar | sein, bleiben, passieren | Ich bin zu Hause geblieben. |
Todos os outros usam **haben**: essen, kaufen, sehen, lernen, arbeiten.
> Pergunta-teste: o sujeito saiu do lugar ou virou outra coisa? Sim → **sein**. Não → **haben**.
# Passo 2: a moldura é a mesma
O auxiliar (agora sein) fica na **2ª posição** e o particípio no **fim**:
~ Ich bin nach Hause gegangen. = Eu fui para casa.
~ Wir sind mit dem Zug gefahren. = Nós fomos de trem.
~ Bist du lange geblieben? = Você ficou muito tempo?
| ich bin gefahren | du bist gefahren | er ist gefahren |
| wir sind gefahren | ihr seid gefahren | sie sind gefahren |
# Passo 3: os particípios mais usados
| Infinitivo | Particípio |
| gehen | gegangen |
| fahren | gefahren |
| fliegen | geflogen |
| kommen | gekommen |
| bleiben | geblieben |
| sein | gewesen |
| aufstehen | aufgestanden |
BR Em português "fui" serve para ir e para ser. Em alemão são verbos diferentes: **ich bin gegangen** (fui, de ir) e **ich bin gewesen** (fui/estive, de ser/estar).
! O erro mais comum é dizer "Ich habe gegangen". Movimento pede sein: **Ich bin gegangen**.
? haben ou sein: Ich ___ nach Berlin gefahren. || bin (movimento)
? haben ou sein: Wir ___ Pizza gegessen. || haben
? Particípio de bleiben || geblieben
`);

// Früher · Präteritum de sein e haben
A(`
Hoje você aprende o jeito mais natural de dizer "eu era", "eu estava" e "eu tinha".
# Passo 1: por que outro passado?
O alemão tem dois passados principais: o **Perfekt** (ich habe gemacht) e o **Präteritum** (ich machte). Na fala, quase tudo vai no Perfekt. Mas **sein e haben** são exceções: até na conversa os alemães preferem o Präteritum, porque é mais curto.
~ Ich war müde. = Eu estava cansada. (mais comum que "Ich bin müde gewesen")
~ Wir hatten keine Zeit. = Nós não tínhamos tempo.
# Passo 2: as formas
| Pessoa | sein | haben |
| ich | war | hatte |
| du | warst | hattest |
| er / sie / es | war | hatte |
| wir | waren | hatten |
| ihr | wart | hattet |
| sie / Sie | waren | hatten |
> Repare: no Präteritum **ich e er são sempre iguais** (ich war, er war). Uma forma a menos para decorar.
# Passo 3: um passado, várias traduções
BR "Ich war in Berlin" pode ser "eu estive em Berlim", "eu estava em Berlim" ou "eu fui a Berlim". O português separa pretérito perfeito e imperfeito; o alemão não. O contexto diz qual é.
# Passo 4: palavras que puxam o passado
| gestern | ontem | früher | antigamente |
| letzte Woche | semana passada | damals | naquela época |
| letztes Jahr | ano passado | als Kind | quando criança |
~ Früher war ich schüchtern, heute bin ich offen. = Antigamente eu era tímida, hoje sou aberta.
~ Als Kind hatte ich einen Hund. = Quando criança eu tinha um cachorro.
? Complete: Gestern ___ ich krank. (sein) || war
? Complete: Wir ___ viel Spaß. (haben) || hatten
? Como se diz "Onde você estava?" || Wo warst du?
`);

// Mit wem? · preposições com dativo
