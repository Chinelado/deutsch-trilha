// Der Mann, der … · orações relativas (nominativo)
A(`
Hoje você aprende a juntar duas frases sobre a mesma pessoa ou coisa: o homem **que** trabalha aqui.
# Passo 1: de duas frases para uma
Das ist der Lehrer. **Der Lehrer** kommt aus Wien.
→ Das ist der Lehrer, **der** aus Wien kommt.
A palavra **der** (que) é o **pronome relativo**. Ela retoma "der Lehrer" e abre a oração relativa.
# Passo 2: o relativo copia o artigo
No nominativo (quando o relativo é o sujeito da relativa), ele é igual ao artigo definido:
| Substantivo | Relativo |
| der Mann | der |
| die Frau | die |
| das Kind | das |
| die Leute (plural) | die |
~ Ich habe eine Freundin, die in Berlin wohnt. = Tenho uma amiga que mora em Berlim.
~ Wo ist das Buch, das hier lag? = Onde está o livro que estava aqui?
# Passo 3: verbo no fim e vírgulas
A relativa é subordinada: verbo conjugado no **fim**. E fica entre vírgulas, logo depois do substantivo, mesmo no meio da frase:
~ Die Frau, die dort wohnt, ist Ärztin. = A mulher que mora ali é médica.
BR Em português "que" serve para tudo. Em alemão o "que" muda conforme o gênero (der, die, das), porque precisa concordar com a palavra retomada.
? Complete: Das ist der Bus, ___ zum Zentrum fährt. || der
? Complete: Ich kenne eine Frau, ___ fünf Sprachen spricht. || die
? Junte: Das ist das Café. Das Café ist neu. || Das ist das Café, das neu ist.
`);

